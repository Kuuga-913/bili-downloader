#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""B 站扫码登录 → 导出登录态 Cookie 给两个下载工具。

运行（用 bilibili-downloader 的 venv Python）：
    python bili_login_qr.py

输出约定：
    QR:xxxx    二维码的一行（纯 ASCII，等宽字体可直接显示）
    [i] ...    状态提示
    [OK] ...   登录成功
    [ERR] ...  失败

成功后在本目录生成：
    cookies.json       -c 可直接加载
    cookies.txt        Netscape 格式，-c 可直接加载，run.bat 会自动识别
    cookie_string.txt  完整 Cookie 串，供图形界面 Cookie 输入框使用
并同步更新 video_spider/config.yaml 里 bilibili 规则的 Cookie（原文件先备份）。
"""
import datetime
import json
import os
import re
import shutil
import sys
import time

import requests
import qrcode

PASSPORT = "https://passport.bilibili.com"
HERE = os.path.dirname(os.path.abspath(__file__))
COOKIES_JSON = os.path.join(HERE, "cookies.json")
COOKIES_TXT = os.path.join(HERE, "cookies.txt")
COOKIE_STRING = os.path.join(HERE, "cookie_string.txt")
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPIDER_CFG = os.path.join(BASE_DIR, "video_spider", "config.yaml")
UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36")


def emit(line=""):
    print(line, flush=True)


def save_cookies(cookies):
    cookie_str = "; ".join("%s=%s" % (k, v) for k, v in cookies.items())
    expires = int(time.time()) + 180 * 24 * 3600

    with open(COOKIES_JSON, "w", encoding="utf-8") as f:
        json.dump(cookies, f, indent=2, ensure_ascii=False)

    lines = ["# Netscape HTTP Cookie File",
             "# generated by bili_login_qr.py at %s" % datetime.datetime.now().isoformat(timespec="seconds"),
             ""]
    for k, v in cookies.items():
        lines.append("\t".join([".bilibili.com", "TRUE", "/", "FALSE",
                                str(expires), k, v]))
    with open(COOKIES_TXT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

    with open(COOKIE_STRING, "w", encoding="utf-8") as f:
        f.write(cookie_str)

    if os.path.exists(SPIDER_CFG):
        with open(SPIDER_CFG, "r", encoding="utf-8") as f:
            text = f.read()
        bak = SPIDER_CFG + ".bak-20261107"
        if not os.path.exists(bak):
            shutil.copy2(SPIDER_CFG, bak)
        lines = text.splitlines(keepends=True)
        replaced = False
        for i, line in enumerate(lines):
            stripped = line.lstrip()
            if stripped.startswith("Cookie:"):
                indent = line[:len(line) - len(stripped)]
                lines[i] = indent + 'Cookie: "' + cookie_str + '"\n'
                replaced = True
                break
        if replaced:
            tmp = SPIDER_CFG + ".tmp"
            with open(tmp, "w", encoding="utf-8", newline="\n") as f:
                f.write("".join(lines))
            os.replace(tmp, SPIDER_CFG)
            emit("[i] 已同步 video_spider/config.yaml（备份: %s）" % os.path.basename(bak))
        else:
            emit("[!] config.yaml 中未找到 Cookie 行，请手动填入 Cookie")
    emit("[i] 已写出 cookies.json / cookies.txt / cookie_string.txt -> %s" % HERE)


def main():
    s = requests.Session()
    s.headers.update({"User-Agent": UA, "Referer": "https://www.bilibili.com/"})
    try:
        j = s.get(PASSPORT + "/x/passport-login/web/qrcode/generate", timeout=30).json()
    except Exception as e:
        emit("[ERR] 获取二维码失败: %s" % e)
        return 1
    if j.get("code") != 0:
        emit("[ERR] 获取二维码失败: %s" % j.get("message"))
        return 1
    key = j["data"]["qrcode_key"]
    url = j["data"]["url"]

    emit("[i] 用手机 B 站 App 扫码并确认（3 分钟内有效）")
    qr = qrcode.QRCode(border=2, box_size=10)
    qr.add_data(url)
    qr.make(fit=True)
    img_path = os.path.join(HERE, "qrcode.png")
    try:
        qr.make_image(fill_color="black", back_color="white").save(img_path)
        emit("[QRIMG] " + img_path)
    except Exception as e:
        emit("[!] 二维码图片生成失败，使用字符二维码: %s" % e)
    for row in qr.get_matrix():
        emit("QR:" + "".join("##" if cell else "  " for cell in row))
    emit("QR:")
    emit("[i] 等待扫码 …")

    deadline = time.time() + 180
    last = ""
    while time.time() < deadline:
        try:
            r = s.get(PASSPORT + "/x/passport-login/web/qrcode/poll",
                      params={"qrcode_key": key}, timeout=30)
            p = r.json()
        except Exception as e:
            emit("[ERR] 扫码轮询失败: %s" % e)
            return 1
        data = p.get("data") or {}
        state = data.get("code")
        if state == 0 and s.cookies.get("SESSDATA"):
            cookies = s.cookies.get_dict()
            save_cookies(cookies)
            emit("[OK] 登录成功，用户ID %s；Cookie 已保存并同步到两个工具"
                 % (data.get("mid", "?")))
            return 0
        status = {86101: "等待扫码 …", 86090: "已扫码，请在手机上确认",
                  86038: "二维码已过期，请重新扫码"}.get(state, "状态 code=%s" % state)
        if status != last:
            emit("[i] " + status)
            last = status
        if state == 86038:
            return 1
        time.sleep(2)
    emit("[ERR] 扫码超时，请重新扫码")
    return 1


if __name__ == "__main__":
    sys.exit(main())
